"""Shared helpers for the deterministic demo workspace generator.

Everything generated by the demo is derived from a fixed namespace plus the
workspace (tenant) id, so the same preset always produces the same identifiers.
Re-running generation is idempotent because :func:`purge_demo` removes the
previously recorded assets before they are recreated.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass, field
from datetime import UTC, datetime
from uuid import UUID, uuid4, uuid5

from app.models import ArchitectureObject, ArchitectureRelationship

DEMO_NAMESPACE = UUID("6d656d6f-d3m0-4000-8000-000000000001".replace("m", "0"))
DEMO_ORIGIN = "synthetic_demo"
DEMO_VERSION = "1.0.0"


def demo_uuid(tenant_id: UUID, key: str) -> UUID:
    """Deterministic UUID for a logical demo asset within one workspace."""
    return uuid5(DEMO_NAMESPACE, f"{tenant_id}:{key}")


@dataclass
class DemoContext:
    """Accumulates generated assets while keeping ids and state graphs stable."""

    tenant_id: UUID
    workspace_id: UUID
    preset: str
    disciplines: set[str]
    db: object | None = None
    now: datetime = field(default_factory=lambda: datetime.now(UTC))
    ids: dict[str, UUID] = field(default_factory=dict)
    assets: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    current_nodes: list[dict] = field(default_factory=list)
    current_relationships: list[dict] = field(default_factory=list)
    candidate_nodes: list[dict] = field(default_factory=list)
    candidate_relationships: list[dict] = field(default_factory=list)
    _node_index: dict[tuple[str, str], int] = field(default_factory=dict)

    def has(self, discipline: str) -> bool:
        return discipline in self.disciplines

    def id(self, key: str) -> UUID:
        value = self.ids.get(key)
        if value is None:
            value = demo_uuid(self.tenant_id, key)
            self.ids[key] = value
        return value

    def record(self, kind: str, asset_id: UUID | str) -> None:
        self.assets[kind].append(str(asset_id))

    def registry(
        self,
        key: str,
        kind: str,
        *,
        system_id: UUID | None = None,
        catalog_object_id: UUID | None = None,
        catalog_field_id: UUID | None = None,
        integration_id: UUID | None = None,
        scenario_id: UUID | None = None,
    ) -> ArchitectureObject:
        row = ArchitectureObject(
            id=self.id(key),
            tenant_id=self.tenant_id,
            kind=kind,
            system_id=system_id,
            catalog_object_id=catalog_object_id,
            catalog_field_id=catalog_field_id,
            integration_id=integration_id,
            scenario_id=scenario_id,
            created_at=self.now,
        )
        self.record("architecture_object", row.id)
        if self.db is not None:
            # Persist registry rows before anything references them, mirroring
            # the service layer which flushes after creating an object.
            self.db.add(row)
            self.db.flush()
        return row

    def relationship(
        self,
        key: str,
        source_object_id: UUID,
        target_object_id: UUID,
        relationship_type: str,
        *,
        created_in_state_id: UUID | None = None,
        properties: dict | None = None,
    ) -> ArchitectureRelationship:
        row = ArchitectureRelationship(
            id=self.id(key),
            tenant_id=self.tenant_id,
            source_object_id=source_object_id,
            target_object_id=target_object_id,
            relationship_type=relationship_type,
            properties=properties or {},
            created_in_state_id=created_in_state_id,
            created_at=self.now,
            updated_at=self.now,
        )
        self.record("relationship", row.id)
        return row

    def add_node(
        self,
        state: str,
        key: str,
        object_id: UUID,
        position: dict[str, float],
        *,
        discipline: str | None = None,
        width: float = 260.0,
        height: float = 140.0,
    ) -> str:
        occurrence_id = f"occ-{object_id}"
        nodes = self.candidate_nodes if state == "candidate" else self.current_nodes
        self._node_index[(state, key)] = len(nodes)
        nodes.append(
            {
                "occurrence_id": occurrence_id,
                "object_id": str(object_id),
                "position": {"x": float(position["x"]), "y": float(position["y"])},
                "discipline": discipline,
                "parent_occurrence_id": None,
                "width": width,
                "height": height,
                "display_metadata": {},
                "candidate_overrides": {},
            }
        )
        return occurrence_id

    def add_state_relationship(
        self,
        state: str,
        key: str,
        source_object_id: UUID,
        target_object_id: UUID,
        relationship_type: str,
        *,
        name: str | None = None,
        integration_id: UUID | None = None,
    ) -> None:
        relationships = (
            self.candidate_relationships if state == "candidate" else self.current_relationships
        )
        relationships.append(
            {
                "id": f"demo-rel-{key}",
                "source_id": str(source_object_id),
                "target_id": str(target_object_id),
                "type": relationship_type,
                "name": name,
                "integration_id": str(integration_id) if integration_id else None,
                "candidate_overrides": {},
                "display_metadata": {},
            }
        )


def new_row_id() -> UUID:
    """Random id for child records whose identity is not logically referenced."""
    return uuid4()
